#!/usr/bin/env python3
"""Build tools/art_origins.json — art_ref -> full-res origin file (+ cell box where needed).

Red-team correction C2 (docs/Realization_Master_Plan.md): the SB# and set2 montage-cell refs
have FULL-RES originals on disk; only the adult#/demon# refs are sheet-cell cuts. Promoting
thumbnail montage cells would upscale already-downscaled art, so this map routes every ref to
the best source that exists:

  * SB#4..SB#33            -> art/storybook/Mutants - Storybook Images/  (sorted order = cell
                              number; files 1-3 are the multi-creature sheets, hence refs start
                              at #4). Verified against contact_sheet_storybook.png +
                              montage_A_4-18/montage_B_19-33 (QA sheet origin_storybook.png).
  * montage_set2_[AB] #S2-N -> art/set2/Mutant Images 2/ (sorted order = S2 number). Verified
                              against montage_set2_A/B cell labels (QA origin_set2_A/B.png).
  * adult#1..10            -> storybook sheet file 1 (1536x1024, 5x2 grid of the ten adults,
                              circled-number badges) — cell box, no higher-res original exists.
  * demon#1..10            -> storybook sheet file 3 (the WHITE-background variant of sheet 2's
                              "10 Unique Monsters" — cleaner knockout source) — cell box.

NOTE (deviation from the plan text): montage_A_4-18.png / montage_B_19-33.png turned out to be
enlarged contact sheets of SB cells 4-18 / 19-33, NOT the adult/demon montages; the adult/demon
cells live in storybook sheet files 1 and 3. Verified visually 2026-07-01.

Usage: python tools/build_art_origins.py [--art-root <main-repo-art>]
"""

from __future__ import annotations

import argparse
import glob
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "tools", "art_origins.json")
DEFAULT_ART_ROOT = "c:/Users/arahi/Documents/Claude/Projects/Mutants_Game/art"
IMG_EXT = (".png", ".jpg", ".jpeg", ".webp")

SHEET_W, SHEET_H = 1536, 1024  # adult/demon sheets: 5 cols x 2 rows
SHEET_COLS, SHEET_ROWS = 5, 2


def list_images(d: str) -> list[str]:
    return sorted(
        f
        for f in glob.glob(os.path.join(d, "**", "*"), recursive=True)
        if f.lower().endswith(IMG_EXT)
    )


def rel_ref(path: str, art_root: str) -> str:
    return os.path.relpath(path, os.path.dirname(art_root)).replace("\\", "/")


def sheet_box(n: int) -> list[int]:
    """1-based cell n of a 5x2 sheet -> [x0, y0, x1, y1]."""
    r, c = divmod(n - 1, SHEET_COLS)
    x0 = c * SHEET_W // SHEET_COLS
    x1 = (c + 1) * SHEET_W // SHEET_COLS
    y0 = r * SHEET_H // SHEET_ROWS
    y1 = (r + 1) * SHEET_H // SHEET_ROWS
    return [x0, y0, x1, y1]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--art-root", default=DEFAULT_ART_ROOT)
    args = ap.parse_args()

    storybook = list_images(os.path.join(args.art_root, "storybook"))
    set2 = list_images(os.path.join(args.art_root, "set2"))
    assert len(storybook) == 33, f"expected 33 storybook files, got {len(storybook)}"
    assert len(set2) == 60, f"expected 60 set2 files, got {len(set2)}"

    refs: dict[str, dict] = {}
    # SB#4..SB#33: sorted file N-1 (0-based) IS cell N
    for n in range(4, 34):
        refs[f"SB#{n}"] = {"file": rel_ref(storybook[n - 1], args.art_root)}
    # set2: S2-1..S2-60 in sorted order; refs split across the A/B montage labels
    for n in range(1, 61):
        label = "montage_set2_A" if n <= 30 else "montage_set2_B"
        refs[f"{label} #S2-{n}"] = {"file": rel_ref(set2[n - 1], args.art_root)}
    # adult#N: storybook sheet 1 cells; demon#N: sheet 3 (white-bg variant) cells
    for n in range(1, 11):
        refs[f"adult#{n}"] = {
            "file": rel_ref(storybook[0], args.art_root),
            "box": sheet_box(n),
        }
        refs[f"demon#{n}"] = {
            "file": rel_ref(storybook[2], args.art_root),
            "box": sheet_box(n),
        }

    payload = {
        "_note": (
            "art_ref -> origin source for the montage-style refs in docs/creature_registry.csv. "
            "Paths are relative to the MAIN repo root (art/ is gitignored in worktrees). "
            "'box' = [x0,y0,x1,y1] cell crop for refs with no standalone original "
            "(adult#/demon# on the 5x2 storybook sheets). Generated by tools/build_art_origins.py; "
            "correspondences verified via labeled QA sheets (see script docstring)."
        ),
        "refs": refs,
    }
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(payload, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"wrote {len(refs)} refs -> {os.path.relpath(OUT, REPO)}")


if __name__ == "__main__":
    main()
