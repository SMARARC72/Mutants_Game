#!/usr/bin/env python3
"""Ingest the authored pantheon boss kits into catalog DATA (Batch E1c).

Parses docs/content/pantheon_kits.md (25 boss kits: 6 Primordials, 9 grid-gods,
10 Olympian/Titan Act bosses) and emits:

  client/catalog/boss_kits.json     {boss_id -> kit data} — species proxy, role,
                                    library-only skill kit, VERBATIM intro/defeat
                                    lines, phase flavor
  client/catalog/region_bosses.json {region_id -> boss_id} — the per-region Act-boss
                                    slot the EncounterCatalog consumes (the integrator
                                    reconciles this with E1b's region_pools boss slot)
  docs/content/_INGEST_NOTES_E1C.md every mapping decision (species proxies, skill
                                    move -> library mappings, region assignments)

CONTRACT (domain untouchable):
  * kits use ONLY skills that already exist in the live SkillEngine library
    (tools/balance_constants.json -> skill.library — the same source that generates
    client/domain/constants.gd). Authored signature moves are mapped to the NEAREST
    existing library skill by (verb, force); every mapping is recorded in the notes.
    NO new skills, NO new numbers.
  * boss species names are AUTHORED pantheon names that do not exist in the 406-species
    registry; each is resolved to a deterministic FORCE-PROXY species (god rank first,
    legendary fallback, exact force-pair before primary-force, registry order, no reuse
    while unused candidates remain). Unresolvable names land on the warn list.
  * intro_line = the boss's Menace quote VERBATIM; defeat_line = the gimmick epigraph
    VERBATIM (the only authored per-boss quotables in the source doc — recorded as a
    decision in the notes).

Deterministic: a re-run over unchanged sources is byte-identical.

Run:  python -B tools/ingest_bosses.py          (writes the catalogs + notes)
      python -B tools/ingest_bosses.py --check  (verifies committed files are current)
"""

