def boss_id_for(doc_id: str, name: str) -> str:
    """Stable snake ids: PR-Gaia -> pr_gaia; OL-11 + Astrapios -> ol_11_astrapios;
    THE LAWGIVER -> gg_lawgiver (gg = grid-god)."""
    if doc_id:
        if doc_id.startswith("PR-"):
            return "pr_" + doc_id[3:].lower()
        first = re.split(r"[,\s]", name.strip())[0].lower()
        return doc_id.replace("OL-", "ol_").lower() + "_" + re.sub(r"[^a-z0-9]", "", first)
    return "gg_" + re.sub(r"[^a-z0-9]+", "_", name.replace("THE ", "").strip().lower()).strip("_")


def parse_meta(meta: str) -> dict:
    """'God · Ouranos/Cosmos' / 'Primordial · Gaia (pure)' / 'God · Construct · Cosmos/Thanatos'."""
    parts = [p.strip() for p in meta.split("·")]
    rank = parts[0].lower()
    construct = any(p.lower() == "construct" for p in parts)
    forces: list[str] = []
    for part in parts[1:]:
        for token in re.split(r"[/\s()]+", part):
            if token in FORCES and token not in forces:
                forces.append(token)
    return {"rank": rank, "construct": construct, "forces": forces}


def parse_bosses(text: str) -> list[dict]:
    bosses: list[dict] = []
    current: dict | None = None
    for line in text.splitlines():
        m = _HEAD_ID_RE.match(line) or _HEAD_GRID_RE.match(line)
        if m:
            groups = m.groupdict()
            doc_id = groups.get("doc_id", "") or ""
            name = groups["name"].strip()
            if not doc_id:
                name = name.title().replace("The ", "The ")
            meta = parse_meta(groups["meta"])
            current = {
                "boss_id": boss_id_for(doc_id, groups["name"].strip()),
                "doc_id": doc_id if doc_id else groups["name"].strip(),
                "name": name if doc_id else "The " + name.replace("The ", "").strip(),
                "rank": meta["rank"],
                "construct": meta["construct"],
                "forces": meta["forces"],
                "grid": (groups.get("grid") or "").strip(),
                "menace": "",
                "gimmick": "",
                "moves": [],
                "phases": {},
                "role_desc": "",
            }
            bosses.append(current)
            continue
        if current is None:
            continue
        if line.startswith("- **Forces / grid:**"):
            d = _ROLE_DESC_RE.search(line)
            current["role_desc"] = d.group("desc") if d else ""
            continue
        m = _MENACE_RE.match(line)
        if m:
            current["menace"] = strip_emphasis(m.group("quote"))
            continue
        m = _GIMMICK_RE.match(line)
        if m:
            current["gimmick"] = strip_emphasis(m.group("epigraph"))
            continue
        m = _PHASE_RE.match(line)
        if m:
            current["phases"][m.group("phase").lower()] = strip_emphasis(
                m.group("flavor").strip().rstrip(".") + "."
            )
            continue
        m = _MOVE_RE.match(line)
        if m:
            verb = (m.group("sig_verb") or m.group("verb") or "").split("→")[0]
            force = (m.group("sig_force") or m.group("force") or "").split("/")[0]
            current["moves"].append(
                {
                    "move": m.group("move").strip(),
                    "verb": verb,
                    "force": force,
                    "signature": m.group("sig_verb") is not None,
                }
            )
    return bosses


def strip_emphasis(text: str) -> str:
    """Strip markdown emphasis markers, keep the words VERBATIM."""
    text = text.replace("**", "")
    text = re.sub(r"(?<![\w])\*|\*(?![\w])", "", text)
    return re.sub(r"\s+", " ", text).strip().strip('"“”').strip()


def derive_role(boss: dict) -> tuple[str, str]:
    """Map the doc's role descriptor to a CombatBrain role. Primordials (no descriptor)
    derive from kit verb weight. Returns (role, how)."""
    desc = boss["role_desc"].lower()
    if "controller" in desc or "control" in desc:
        return "controller", "descriptor %r" % boss["role_desc"]
    for token in ("nuker", "executioner", "striker", "disruptor", "aggressor"):
        if token in desc:
            return "aggressor", "descriptor %r" % boss["role_desc"]
    for token in ("warder", "tank", "fortress", "regenerator", "healer", "sustain", "warden"):
        if token in desc:
            return "support", "descriptor %r" % boss["role_desc"]
    offense = sum(1 for mv in boss["moves"] if mv["verb"] in ("Strike", "Drain", "Gambit"))
    control = sum(1 for mv in boss["moves"] if mv["verb"] == "Hex")
    defense = sum(1 for mv in boss["moves"] if mv["verb"] in ("Ward", "Mend", "Rouse"))
    if offense > control and offense > defense:
        return "aggressor", "kit verbs (offense %d/control %d/defense %d)" % (offense, control, defense)
    if defense > control and defense > offense:
        return "support", "kit verbs (offense %d/control %d/defense %d)" % (offense, control, defense)
    return "controller", "kit verbs (offense %d/control %d/defense %d)" % (offense, control, defense)


def map_move(move: dict, library: dict, notes: list[str], boss_id: str) -> str:
    """The nearest existing library skill for an authored move. Records the mapping."""
    key = (move["verb"], move["force"])
    skill = VERB_FORCE_TO_SKILL.get(key, "")
    how = "verb+force"
    if not skill:
        # Fall back to the first library skill of the move's force (insertion order).
        for name, spec in library.items():
            if spec.get("force") == move["force"]:
                skill = name
                how = "force-pool fallback"
                break
    if not skill:
        notes.append(
            "- **UNMAPPED** `%s` · %s (%s, %s) — no library skill of that force"
            % (boss_id, move["move"], move["verb"], move["force"])
        )
        return ""
    exact = move["move"] == skill
    notes.append(
        "- `%s` · %s (%s, %s) → **%s**%s"
        % (
            boss_id,
            move["move"],
            move["verb"],
            move["force"],
            skill,
            " (verbatim library skill)" if exact else " (%s)" % how,
        )
    )
    return skill


def resolve_species(bosses: list[dict], species: list[dict], notes: list[str]) -> list[str]:
    """Deterministic force-proxy resolution. Exact authored names never exist in the
    registry (verified); resolve by (rank, force pair) then (rank, primary force),
    god rank before legendary, registry order, preferring unused candidates."""
    by_name = {s.get("name", ""): s for s in species}
    used: set[str] = set()
    warn: list[str] = []
    for boss in bosses:
        exact = by_name.get(boss["name"])
        if exact is not None:
            boss["species_id"] = str(exact["id"])
            boss["species_resolution"] = "exact"
            used.add(boss["species_id"])
            notes.append("- `%s` → %s (exact name match)" % (boss["boss_id"], exact["id"]))
            continue
        prim = boss["forces"][0] if boss["forces"] else ""
        sec = boss["forces"][1] if len(boss["forces"]) > 1 else None
        candidate = _pick_proxy(species, used, prim, sec)
        if candidate is None:
            boss["species_id"] = ""
            boss["species_resolution"] = "unresolved"
            warn.append(boss["boss_id"])
            notes.append("- **UNRESOLVED** `%s` (%s) — no god/legendary proxy" % (boss["boss_id"], boss["name"]))
            continue
        boss["species_id"] = str(candidate["id"])
        boss["species_resolution"] = "force_proxy"
        used.add(boss["species_id"])
        notes.append(
            "- `%s` (%s · %s) → **%s** %r (%s %s/%s force-proxy)"
            % (
                boss["boss_id"],
                boss["name"],
                "/".join(boss["forces"]),
                candidate["id"],
                candidate.get("name", ""),
                candidate.get("rank", ""),
                candidate.get("force_primary", ""),
                candidate.get("force_secondary", "") or "-",
            )
        )
    return warn


def _pick_proxy(species: list[dict], used: set, prim: str, sec: str | None) -> dict | None:
    """Best proxy in strict preference order; within a tier prefer an unused id, then
    registry order (both deterministic)."""
    tiers = [
        ("god", True),  # exact (prim, sec) pair
        ("legendary", True),
        ("god", False),  # primary force only
        ("legendary", False),
    ]
    for rank, need_pair in tiers:
        pool = [
            s
            for s in species
            if s.get("rank") == rank
            and s.get("force_primary") == prim
            and (not need_pair or _sec_matches(s, sec))
        ]
        for candidate in pool:  # prefer unused, in registry order
            if str(candidate["id"]) not in used:
                return candidate
        if pool:
            return pool[0]
    return None


def _sec_matches(s: dict, sec: str | None) -> bool:
    reg_sec = s.get("force_secondary") or None
    return reg_sec == sec


def build(check: bool) -> int:
    with open(SOURCE, encoding="utf-8") as fh:
        text = fh.read()
    with open(SPECIES, encoding="utf-8") as fh:
        species = json.load(fh)["species"]
    with open(BALANCE, encoding="utf-8") as fh:
        library = json.load(fh)["skill"]["library"]

    bosses = parse_bosses(text)
    if len(bosses) != 25:
        print("ERROR: expected 25 bosses, parsed %d" % len(bosses), file=sys.stderr)
        return 1

    skill_notes: list[str] = []
    species_notes: list[str] = []
    role_notes: list[str] = []
    warn = resolve_species(bosses, species, species_notes)

    region_of = {}
    for region, (boss_id, _why) in REGION_BOSSES.items():
        region_of[boss_id] = region

    out_bosses = []
    for boss in bosses:
        role, how = derive_role(boss)
        role_notes.append("- `%s` → **%s** (%s)" % (boss["boss_id"], role, how))
        kit: list[str] = []
        signature = ""
        for mv in boss["moves"]:
            skill = map_move(mv, library, skill_notes, boss["boss_id"])
            if skill and skill not in kit:
                kit.append(skill)
            if mv["signature"] and skill:
                signature = skill
        out_bosses.append(
            {
                "boss_id": boss["boss_id"],
                "doc_id": boss["doc_id"],
                "name": boss["name"],
                "rank": boss["rank"],
                "construct": boss["construct"],
                "forces": boss["forces"],
                "grid": boss["grid"],
                "region": region_of.get(boss["boss_id"], ""),
                "species_id": boss["species_id"],
                "species_resolution": boss["species_resolution"],
                "role": role,
                "kit": kit,
                "signature_skill": signature,
                "signature_move": next(
                    (mv["move"] for mv in boss["moves"] if mv["signature"]), ""
                ),
                "intro_line": boss["menace"],
                "defeat_line": boss["gimmick"],
                "phase_flavor": boss["phases"],
            }
        )

    kits_doc = {
        "_generated": GENERATED,
        "_contract": (
            "DATA ONLY — kits name existing Constants.BALANCE.skill.library skills; species_id "
            "is a deterministic registry force-proxy for the authored pantheon name (the boss "
            "keeps its authored name via the encounter nickname); intro_line/defeat_line are "
            "VERBATIM authored lines (Menace quote / gimmick epigraph)."
        ),
        "unresolved": warn,
        "bosses": out_bosses,
    }
    regions_doc = {
        "_generated": GENERATED,
        "_contract": (
            "region_id -> boss_id (boss_kits.json). The verdant slot is informational: "
            "slice_verdant.json's wired Legendary keeps precedence in EncounterCatalog. "
            "maw_beneath/hollow_atelier are reserved keys until their regions land. The "
            "integrator reconciles this with E1b's region_pools boss slot."
        ),
        "region_bosses": {region: boss for region, (boss, _w) in sorted(REGION_BOSSES.items())},
    }

    notes = [
        "# _INGEST_NOTES_E1C — boss kits & region bosses",
        "",
        GENERATED + ".",
        "",
        "## Decisions",
        "",
        "- **intro_line** = the boss's `Menace` quote VERBATIM; **defeat_line** = the gimmick",
        "  epigraph VERBATIM — the only authored per-boss quotables in pantheon_kits.md.",
        "- **Scene id naming convention** (shared with E1a's generated timelines, so the",
        "  integrator can reconcile): `<npc_snake_case>_<beat>` (e.g. `sub_registrar_ottle_greyquill_intro`).",
        "  npc_casts.json references timelines by that convention; the overworld falls back to",
        "  the NPC's authored barks until the timeline resource exists.",
        "- **Roles** map the doc's role descriptor onto the CombatBrain vocabulary",
        "  (aggressor/support/controller); Primordials (no descriptor) derive from kit verb weight.",
        "- **Kit skills** map every authored move to the NEAREST existing library skill by",
        "  (primary verb, first force); no Gaia Hex / no Summon verb exists, so The Long Settling",
        "  → Bind and Summon: Forged Servitor → Aegis are recorded approximations.",
        "",
        "## Region boss assignments (client/catalog/region_bosses.json)",
        "",
    ]
    for region in sorted(REGION_BOSSES):
        boss_id, why = REGION_BOSSES[region]
        notes.append("- `%s` → `%s` — %s" % (region, boss_id, why))
    notes += ["", "## Species force-proxy resolutions", ""]
    notes += species_notes
    notes += ["", "## Role derivations", ""]
    notes += role_notes
    notes += ["", "## Move → library-skill mappings", ""]
    notes += skill_notes
    notes_text = "\n".join(notes) + "\n"

    outputs = [
        (OUT_KITS, json.dumps(kits_doc, ensure_ascii=False, indent=2) + "\n"),
        (OUT_REGIONS, json.dumps(regions_doc, ensure_ascii=False, indent=2) + "\n"),
        (OUT_NOTES, notes_text),
    ]
    if check:
        stale = []
        for path, payload in outputs:
            current = ""
            if os.path.exists(path):
                with open(path, encoding="utf-8") as fh:
                    current = fh.read()
            if current != payload:
                stale.append(os.path.relpath(path, ROOT))
        if stale:
            print("STALE: %s (re-run tools/ingest_bosses.py)" % ", ".join(stale), file=sys.stderr)
            return 1
        print("boss_kits.json / region_bosses.json / notes are current.")
        return 0
    for path, payload in outputs:
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(payload)
    print(
        "wrote %d bosses (%d unresolved), %d region slots"
        % (len(out_bosses), len(warn), len(REGION_BOSSES))
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    return build(args.check)


if __name__ == "__main__":
    sys.exit(main())
