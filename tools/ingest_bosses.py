# --- boss heading formats --------------------------------------------------------------------- #
# §1/§3:  ### PR-Gaia — Gaia, the True Ground · **Primordial · Gaia (pure)**
#         ### OL-11 — Astrapios, the Sky-Sovereign · **God · Ouranos/Cosmos** *(canonical ...)*
# §2:     ### THE LAWGIVER (Order · Pure) — Law/Heaven · **God · Gaia/Ouranos**
_HEAD_ID_RE = re.compile(r"^### (?P<doc_id>(?:PR|OL)-[\w]+) — (?P<name>[^·]+?) · \*\*(?P<meta>[^*]+)\*\*")
_HEAD_GRID_RE = re.compile(r"^### (?P<name>THE [A-Z ]+?) \((?P<grid>[^)]+)\) — [^·]+· \*\*(?P<meta>[^*]+)\*\*")

_MENACE_RE = re.compile(r"^- \*\*Menace:\*\* \*(?P<quote>.+?)\*\s*$")
_GIMMICK_RE = re.compile(r"^- \*\*The gimmick — \*(?P<epigraph>.+?)\*\*\*")
_MOVE_RE = re.compile(
    r"^\s+- \*\*(?P<move>[^*]+)\*\*\s*"
    r"(?:\*\(signature — (?P<sig_verb>[\w→]+), (?P<sig_force>[\w/]+)\)\*"
    r"|\((?P<verb>[\w→]+), (?P<force>[\w/]+)\))"
)
_PHASE_RE = re.compile(
    r"^\s+- \*\*(?P<phase>Opening|Pressure|Desperation|Apotheosis)\*\* \(`(?P<gate>[^`]*)`\)"
    r" — (?P<flavor>.+?)(?: → | →$|$)"
)
_ROLE_DESC_RE = re.compile(r"\((?P<desc>[^)]*?(?:;| HP )[^)]*)\)")

FORCES = ("Gaia", "Ouranos", "Cosmos", "Chaos", "Eros", "Thanatos")

# The CombatBrain role vocabulary (role_brains.for_role) — the ONLY legal role values.
VALID_ROLES = ("aggressor", "support", "controller", "unpredictable", "neutral")

# (verb, force) -> the nearest EXISTING library skill. Compound verbs (Ward→Hex) map by
# their PRIMARY verb; multi-force moves (Cosmos/Gaia) map by their FIRST force. Where the
# library has no skill of that (verb, force), the row names the recorded approximation.
VERB_FORCE_TO_SKILL = {
    ("Strike", "Chaos"): "Riot Fang",
    ("Strike", "Gaia"): "Boulder Smash",
    ("Strike", "Ouranos"): "Gale Slash",
    ("Ward", "Cosmos"): "Aegis",
    ("Ward", "Gaia"): "Bulwark",
    ("Hex", "Cosmos"): "Bind",
    ("Hex", "Thanatos"): "Wither",
    # No Gaia Hex exists in the library; Bind is the nearest control verb (recorded).
    ("Hex", "Gaia"): "Bind",
    ("Mend", "Eros"): "Bloom",
    ("Rouse", "Ouranos"): "Tailwind",
    ("Rouse", "Eros"): "Verdant Gift",
    ("Drain", "Thanatos"): "Soul Leech",
    ("Gambit", "Chaos"): "Overload",
    # No Summon verb exists in the library; the Forged Servitor add is expressed as the
    # Cosmos ward it provides (recorded).
    ("Summon", "Cosmos"): "Aegis",
}

