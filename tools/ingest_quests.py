#!/usr/bin/env python3
"""Ingest the authored quest docs into the quest catalog (Batch E1a).

Parses docs/content/story_quests.md (the 6-act main spine, 24 quests) and
docs/content/side_quests.md (28 side quests) and emits client/catalog/quests.json:
every quest as {id, kind, act, region, title, giver_npc, prereq_flags,
steps:[{id, step_key, objective_text, on_complete}], on_complete}.

Objective / title / giver text lands VERBATIM (only markdown emphasis markers are
stripped — the voice-ingest precedent). Where the doc is structurally ambiguous the
tool makes the CONSERVATIVE choice and records it in tools/INGEST_NOTES.md (between
its ownership markers) — no silent inventions:
  * one step per quest (the docs author one Objective line per quest; branch
    variations are scene/dialogue-layer effects, as the wired SQ-05/Act-0 pattern);
  * main-quest act gates: quest X.4 (the authored "Act climax") sets act<X+1>_open
    on completion; within an act the quests chain linearly (X.Y needs act<X>_q<Y-1>_done);
  * side quests are region-gated, not act-gated (the docs state no act);
  * standing/corruption/grid rewards stay OUT of quest defs: every standing line in
    the docs is BRANCH-gated ("running it clean...", "selling out grants..."), and
    branch effects live on dialogue-choice configs (the wired Old Garran / Vael
    Mark pattern) — the tool lists each detected standing phrase in the notes
    instead of emitting a fork's reward unconditionally.

Deterministic: a re-run over unchanged sources is byte-identical (sorted ordering,
LF newlines, no timestamps).

Run:  python -B tools/ingest_quests.py          (writes client/catalog/quests.json)
      python -B tools/ingest_quests.py --check  (verifies the committed file is current)
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STORY_PATH = os.path.join(ROOT, "docs", "content", "story_quests.md")
SIDE_PATH = os.path.join(ROOT, "docs", "content", "side_quests.md")
CAST_PATHS = [
    os.path.join(ROOT, "docs", "content", "regional_cast.md"),
    os.path.join(ROOT, "docs", "content", "factions_npcs.md"),
]
OUT_PATH = os.path.join(ROOT, "client", "catalog", "quests.json")
NOTES_PATH = os.path.join(ROOT, "tools", "INGEST_NOTES.md")
NOTES_BEGIN = "<!-- BEGIN ingest_quests.py (generated warn-lists — do not edit) -->"
NOTES_END = "<!-- END ingest_quests.py -->"

GENERATED_HEADER = (
    "GENERATED by tools/ingest_quests.py from docs/content/story_quests.md + "
    "docs/content/side_quests.md — edit the source, re-run the tool."
)

# Canonical region names (regions.md §1-11) -> engine region ids.
REGIONS = {
    "threshold": "threshold",
    "verdant glut": "verdant_glut",
    "mournmarch": "mournmarch",
    "forgefell": "forgefell",
    "storm vault": "storm_vault",
    "sunder": "sunder",
    "titanfall": "titanfall",
    "tideless": "tideless",
    "astral tier": "astral_tier",
    "maw beneath": "maw_beneath",
    "hollow atelier": "hollow_atelier",
}

# Canonical faction ids (client/catalog/factions.json). Standing rewards are
# emitted ONLY when a doc phrase names one of these unambiguously.
FACTIONS = {
    "concord": "concord",
    "iron guild": "iron_guild",
    "pale court": "pale_court",
    "high table": "high_table",
    "stoneblooded": "stoneblooded",
    "bloomwarden": "bloomwardens",
    "bloomwardens": "bloomwardens",
    "revel": "revel",
    "unbound": "unbound",
    "deep choir": "deep_choir",
}

_EMPH_RE = re.compile(r"\*\*|\*|`")
_ACT_RE = re.compile(r"^# ACT (\d+) — ")
_MAIN_Q_RE = re.compile(r"^### Quest (\d+)\.(\d+) — \"([^\"]+)\"")
_SIDE_Q_RE = re.compile(
    r"^### SQ-(\d+) · \"([^\"]+)\" · `\[(\w+)\]` · ([^·]+?) · Giver: (.+)$"
)
_FIELD_RE = re.compile(r"^- \*\*([^*]+?):?\*\*:?\s*(.*)$")
_BOLD_RE = re.compile(r"\*\*([^*]+?)\*\*")
_REGION_PAREN_RE = re.compile(r"\(([^()·]+?) · [^()]*\)")
_STANDING_RE = re.compile(
    r"(?:advances\s+|\+1\s+)([A-Za-z ]+?)\s+standing", re.IGNORECASE
)


def strip_emphasis(text: str) -> str:
    """Markdown emphasis markers off; the words stay verbatim."""
    return _EMPH_RE.sub("", text).strip()


def slug(text: str, cap: int = 48) -> str:
    """Deterministic id fragment from a title (apostrophes drop, not split)."""
    text = text.strip().lower()
    text = re.sub(r"[''`]", "", text)
    text = re.sub(r"[^a-z0-9]+", "_", text).strip("_")
    if len(text) > cap:
        cut_mid_word = text[cap] != "_"
        text = text[:cap].rstrip("_")
        if cut_mid_word and "_" in text:
            text = text.rsplit("_", 1)[0]
    return text


def region_id(name: str) -> str:
    key = re.sub(r"^the\s+", "", strip_emphasis(name).strip().lower()).strip()
    return REGIONS.get(key, "")


def field_lines(lines: list[str]) -> dict:
    """The '- **Label:** value' fields of one quest block (first wins)."""
    fields: dict = {}
    for line in lines:
        m = _FIELD_RE.match(line)
        if m:
            label = m.group(1).strip().lower()
            if label not in fields:
                fields[label] = m.group(2).strip()
    return fields


def giver_from(text: str) -> str:
    """First name-like bold in a quest-giver line (VERBATIM), else the first
    bold at all, else ''. 'Name-like' = Title-cased (not an ALL-CAPS mode tag,
    not a lowercase role phrase, not a '... faction' placeholder)."""
    bolds = [strip_emphasis(b) for b in _BOLD_RE.findall(text)]
    for b in bolds:
        if not b or b == b.upper() or b.lower().endswith("faction"):
            continue
        if b[0].isupper():
            return b
    return bolds[0] if bolds else ""


def main_region_from(giver_line: str, act: int) -> str:
    """Region for a main quest: the '(Region · God)' tag in the giver line when
    it precedes any 'e.g.' (faction-dependent quests stay region-agnostic);
    Act 0 defaults to Threshold (the authored hub)."""
    head = giver_line.split("e.g.")[0]
    for cand in _REGION_PAREN_RE.findall(head):
        rid = region_id(cand)
        if rid:
            return rid
    return "threshold" if act == 0 else ""


def standing_mentions(gate_text: str) -> list[str]:
    """Canonical faction ids named by standing phrases in a Gate/Reward line.
    Detected for the notes ONLY — every such line in the docs is branch-gated,
    so the reward belongs to the dialogue-choice layer, not the quest def."""
    out: list[str] = []
    for name in _STANDING_RE.findall(gate_text):
        fid = FACTIONS.get(name.strip().lower())
        if fid and fid not in out:
            out.append(fid)
    return out


def parse_story(text: str) -> list[dict]:
    quests: list[dict] = []
    act = -1
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        act_m = _ACT_RE.match(line)
        if act_m:
            act = int(act_m.group(1))
            i += 1
            continue
        q_m = _MAIN_Q_RE.match(line)
        if not q_m:
            i += 1
            continue
        q_act, q_num, title = int(q_m.group(1)), int(q_m.group(2)), q_m.group(3)
        block: list[str] = []
        i += 1
        while i < len(lines) and not lines[i].startswith("#"):
            block.append(lines[i])
            i += 1
        fields = field_lines(block)
        giver_line = fields.get("quest-giver", "")
        qid = "act%d_%s" % (q_act, slug(title))
        # Act-gate chain (recorded in INGEST_NOTES): X.1 needs act<X>_open (X>0);
        # X.Y>1 needs the previous quest's done-flag; X.4 opens the next act.
        prereq: list[str] = []
        if q_num == 1 and q_act > 0:
            prereq = ["act%d_open" % q_act]
        elif q_num > 1:
            prereq = ["act%d_q%d_done" % (q_act, q_num - 1)]
        if q_num == 4 and q_act < 5:
            gate_flag = "act%d_open" % (q_act + 1)
        else:
            gate_flag = "act%d_q%d_done" % (q_act, q_num)
        quests.append(
            {
                "id": qid,
                "kind": "main",
                "act": q_act,
                "q": q_num,
                "region": main_region_from(giver_line, q_act),
                "title": strip_emphasis(title),
                "giver_npc": giver_from(giver_line),
                "prereq_flags": prereq,
                "steps": [
                    {
                        "id": "objective",
                        "step_key": qid + "_step",
                        "objective_text": strip_emphasis(fields.get("objective", "")),
                        "on_complete": {},
                    }
                ],
                "on_complete": {"set_flag": gate_flag},
            }
        )
    return quests


def parse_side(text: str) -> list[dict]:
    quests: list[dict] = []
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        m = _SIDE_Q_RE.match(lines[i])
        if not m:
            i += 1
            continue
        number, title, qtype, region_name, giver_part = m.groups()
        block: list[str] = []
        i += 1
        while i < len(lines) and not lines[i].startswith("#"):
            block.append(lines[i])
            i += 1
        fields = field_lines(block)
        qid = slug(title)
        quests.append(
            {
                "id": qid,
                "kind": "side",
                "sq": int(number),
                "type": qtype.lower(),
                "standing_mentions": standing_mentions(fields.get("gate / reward", "")),
                # Side quests state no act — region access is their gate
                # (recorded in INGEST_NOTES). act -1 = "not act-gated".
                "act": -1,
                "region": region_id(region_name),
                "title": strip_emphasis(title),
                "giver_npc": giver_from(giver_part),
                "prereq_flags": [],
                "steps": [
                    {
                        "id": "objective",
                        "step_key": qid + "_step",
                        "objective_text": strip_emphasis(fields.get("objective", "")),
                        "on_complete": {},
                    }
                ],
                "on_complete": {"set_flag": qid + "_done"},
            }
        )
    return quests


def cast_warn_list(quests: list[dict]) -> list[str]:
    """Giver names not found in the cast docs (regional_cast + factions_npcs +
    story_quests itself for the net-new-authored mentors) — warn, never fail."""
    corpus = ""
    for path in CAST_PATHS:
        with open(path, "r", encoding="utf-8") as fh:
            corpus += fh.read().lower()
    missing: list[str] = []
    for q in quests:
        giver = q["giver_npc"]
        if not giver:
            missing.append("%s: (no giver parsed)" % q["id"])
            continue
        probes = [giver.lower()]
        # Compound titles ("Madam Cessil, the Threshold Astrologer") probe the
        # name segment; multi-word names also probe the bare surname.
        probes.append(giver.split(",")[0].strip().lower())
        words = giver.split(",")[0].split()
        if len(words) >= 2:
            probes.append(" ".join(words[-2:]).lower())
        if not any(p and p in corpus for p in probes):
            missing.append("%s: %s" % (q["id"], giver))
    return missing


def notes_section(main: list[dict], side: list[dict], missing: list[str]) -> str:
    by_act: dict = {}
    for q in main:
        by_act[q["act"]] = by_act.get(q["act"], 0) + 1
    act_line = " · ".join("act %d: %d" % (a, by_act[a]) for a in sorted(by_act))
    out = [NOTES_BEGIN, ""]
    out.append(
        "**Counts (actuals):** %d main (%s) · %d side. Docs promise 24 main / 28 side."
        % (len(main), act_line, len(side))
    )
    out.append("")
    standing = [
        "%s -> %s" % (q["id"], "/".join(q["standing_mentions"]))
        for q in side
        if q["standing_mentions"]
    ]
    out.append(
        "**Standing phrases detected (branch-gated in the doc — surfaced for the "
        "dialogue-choice wiring, NOT emitted as unconditional quest rewards):** "
        + ("; ".join(standing) if standing else "(none)")
    )
    out.append("")
    out.append(
        "**Giver warn-list (not found in regional_cast.md / factions_npcs.md — "
        "story_quests.md names are net-new authored per its own canon-gap note; "
        "reconcile via _NAME_RECONCILIATION.md, do not invent):**"
    )
    if missing:
        out.extend("- " + m for m in missing)
    else:
        out.append("- (none)")
    out.append("")
    out.append(NOTES_END)
    return "\n".join(out)


def splice_notes(section: str) -> None:
    """Replace this tool's marker-delimited section of INGEST_NOTES.md in place."""
    with open(NOTES_PATH, "r", encoding="utf-8") as fh:
        text = fh.read()
    begin = text.find(NOTES_BEGIN)
    end = text.find(NOTES_END)
    if begin < 0 or end < 0:
        raise SystemExit("INGEST_NOTES.md is missing the ingest_quests.py markers")
    new_text = text[:begin] + section + text[end + len(NOTES_END) :]
    with open(NOTES_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(new_text)


def build() -> tuple[str, str]:
    with open(STORY_PATH, "r", encoding="utf-8") as fh:
        main = parse_story(fh.read())
    with open(SIDE_PATH, "r", encoding="utf-8") as fh:
        side = parse_side(fh.read())
    ids = [q["id"] for q in main + side]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SystemExit("duplicate quest ids: %s" % ", ".join(dupes))
    quests = sorted(
        main, key=lambda q: (q["act"], q["q"])
    ) + sorted(side, key=lambda q: q["sq"])
    payload = {
        "_generated": GENERATED_HEADER,
        "counts": {"main": len(main), "side": len(side)},
        "quests": quests,
    }
    catalog = json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    notes = notes_section(main, side, cast_warn_list(main + side))
    return catalog, notes


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog, notes = build()
    if args.check:
        with open(OUT_PATH, "r", encoding="utf-8") as fh:
            if fh.read() != catalog:
                print("STALE: client/catalog/quests.json — re-run tools/ingest_quests.py")
                return 1
        print("quests.json is current")
        return 0
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(catalog)
    splice_notes(notes)
    data = json.loads(catalog)
    print(
        "wrote %s: %d main + %d side quests"
        % (
            os.path.relpath(OUT_PATH, ROOT),
            data["counts"]["main"],
            data["counts"]["side"],
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
