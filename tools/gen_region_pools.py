ROLE_TO_BRAIN = {
    "tank": "controller",
    "control": "controller",
    "controller": "controller",
    "fortress": "controller",
    "control-tank": "controller",
    "support": "support",
    "seer": "support",
    "regenerator": "support",
}
DEFAULT_BRAIN = "aggressor"  # strikers/nukers/assassins/bruisers/chargers play to kill

# Pool caps (the slice_verdant scale: ~18 wild + ~5 elite reads well in the encounter UI).
LOW_TIER_CAP = 12
HIGH_TIER_CAP = 6
SINGLE_TIER_CAP = 14
ELITE_CAP = 5
MIN_STRICT = 8  # a strict force-blend pool below this relaxes to the standard match

BASE_WEIGHT = {"T1": 5, "T2": 3, "T3": 2}


def load_registry() -> list[dict]:
    with REGISTRY.open(newline="", encoding="utf-8") as f:
        rows = [row for row in csv.DictReader(f)]
    # Drop unusable rows: no id, or an unshippable status. "confirmed"/"reviewed" both ship.
    return [
        r
        for r in rows
        if (r.get("id") or "").strip() and (r.get("status") or "").strip() not in ("void", "draft")
    ]


def force_match(row: dict, forces: list[str], strict: bool) -> bool:
    primary = (row.get("force_primary") or "").strip()
    secondary = (row.get("force_secondary") or "").strip()
    if strict:
        return primary in forces and secondary in forces and primary != secondary
    return primary in forces or secondary in forces


def weight_of(row: dict) -> int:
    tier = (row.get("tier") or "").strip()
    weight = BASE_WEIGHT.get(tier, 2)
    if "apex" in (row.get("tags") or ""):
        weight -= 1  # apexes are the rarer sighting
    if (row.get("status") or "").strip() == "confirmed":
        weight += 1  # the confirmed canon spine reads a touch more often
    return max(1, weight)


def wild_candidates(rows: list[dict], spec: dict) -> list[dict]:
    strict = bool(spec.get("strict_blend", False))
    out = [
        r
        for r in rows
        if (r.get("rank") or "").strip() == "wild"
        and (r.get("tier") or "").strip() in spec["band"]
        and (bool(spec.get("construct", False)) == ((r.get("class") or "").strip() == "construct"))
        and force_match(r, spec["forces"], strict)
    ]
    if strict and len(out) < MIN_STRICT:
        return wild_candidates(rows, {**spec, "strict_blend": False})
    return out


def pool_entry(row: dict) -> dict:
    return {
        "species_id": row["id"],
        "weight": weight_of(row),
        "tier": (row.get("tier") or "").strip(),
        "role": (row.get("role") or "").strip() or "support",
    }


def build_wild_pool(candidates: list[dict], band: list[str]) -> list[dict]:
    by_tier: dict[str, list[dict]] = {t: [] for t in band}
    for row in sorted(candidates, key=lambda r: r["id"]):
        by_tier[(row.get("tier") or "").strip()].append(row)
    picked: list[dict] = []
    if len(band) == 1:
        picked = by_tier[band[0]][:SINGLE_TIER_CAP]
    else:
        picked = by_tier[band[0]][:LOW_TIER_CAP] + by_tier[band[1]][:HIGH_TIER_CAP]
    return [pool_entry(r) for r in picked]


def build_elite_pool(rows: list[dict], spec: dict, wild_ids: set[str]) -> list[dict]:
    if not spec.get("elite", False):
        return []
    candidates = [
        r
        for r in rows
        if (r.get("rank") or "").strip() == "wild"
        and (r.get("tier") or "").strip() == "T3"
        and r["id"] not in wild_ids
        and (bool(spec.get("construct", False)) == ((r.get("class") or "").strip() == "construct"))
        and force_match(r, spec["forces"], False)
    ]
    # Apex-tagged elites first (the veil coughs up the region's worst), then plain T3, id-sorted.
    # A high-band region may have folded most of its T3s into the wild pool already; rather than
    # ship a threadbare elite table, refill from those wild T3s (an overlap is harmless - the
    # misbehavior draw just replaces the party with ONE elite).
    candidates.sort(key=lambda r: (0 if "apex" in (r.get("tags") or "") else 1, r["id"]))
    if len(candidates) < ELITE_CAP:
        seen = {r["id"] for r in candidates}
        refill = [
            r
            for r in rows
            if (r.get("rank") or "").strip() == "wild"
            and (r.get("tier") or "").strip() == "T3"
            and r["id"] in wild_ids
            and r["id"] not in seen
            and force_match(r, spec["forces"], False)
        ]
        refill.sort(key=lambda r: (0 if "apex" in (r.get("tags") or "") else 1, r["id"]))
        candidates += refill
    out = []
    for i, row in enumerate(candidates[:ELITE_CAP]):
        entry = pool_entry(row)
        entry["weight"] = 3 if i == 0 else 2
        out.append(entry)
    return out


def build_boss(rows_by_id: dict[str, dict], region_id: str) -> dict:
    species_id, kit_id, kit = BOSSES[region_id]
    row = rows_by_id[species_id]
    role = (row.get("role") or "").strip() or "tank"
    return {
        "species_id": species_id,
        "name": row["name"],
        "rank": (row.get("rank") or "").strip() or "legendary",
        "role": role,
        "brain": ROLE_TO_BRAIN.get(role, DEFAULT_BRAIN),
        "kit_id": kit_id,
        "kit": kit,
    }


def build_trigger(region_id: str) -> dict:
    # The hub's climax (the Arena exhibition bout) sits deeper than a field region's lair.
    return {
        "min_steps": 40 if region_id == "threshold" else 30,
        "cleared_flag": "%s_boss_cleared" % region_id,
        "victory_flag": "%s_boss_victory" % region_id,
    }


def main() -> None:
    rows = load_registry()
    rows_by_id = {r["id"]: r for r in rows}
    regions: dict[str, dict] = {}
    for region_id, spec in REGIONS.items():
        candidates = wild_candidates(rows, spec)
        wild = build_wild_pool(candidates, spec["band"])
        wild_ids = {e["species_id"] for e in wild}
        elite = build_elite_pool(rows, spec, wild_ids)
        boss = build_boss(rows_by_id, region_id)
        if not wild:
            raise SystemExit("EMPTY wild pool for %s - widen the spec" % region_id)
        regions[region_id] = {
            "_doc": spec["_doc"],
            "forces": spec["forces"],
            "tier_band": spec["band"],
            "wild_pool": wild,
            "elite_pool": elite,
            "boss": boss,
            "boss_trigger": build_trigger(region_id),
        }
        print(
            "%-15s wild=%2d elite=%d boss=%s (%s)"
            % (region_id, len(wild), len(elite), boss["species_id"], boss["name"])
        )
    payload = {
        "_generated": HEADER,
        "_doc": (
            "Per-region encounter pools for the ten non-verdant regions (verdant_glut ships in "
            "slice_verdant.json). Same shape as the slice: weighted wild_pool rows, a T3 "
            "elite_pool, the boss slot + its deterministic step trigger. Served by "
            "EncounterCatalog through the same API for ANY region."
        ),
        "schema_version": 1,
        "regions": regions,
    }
    OUT.write_text(json.dumps(payload, indent="\t", ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote %s" % OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
