#!/usr/bin/env python3
"""Ingest the authored regional casts into catalog DATA (Batch E1c).

Parses docs/content/regional_cast.md (the +43 living-world NPCs, per region) and
docs/content/factions_npcs.md (the 64-NPC layer: 9 faction leaders + 27 Hands +
the PART TWO roster + wanderers) and emits client/catalog/npc_casts.json:

  { "regions": { "<region_id>": [ {name, role, faction, title?, ring, timeline,
                                   bark_key, barks, source}, ... ],
                 "wanderers": [...] } }

CONTRACT:
  * NPC names/roles/barks land VERBATIM (markdown emphasis stripped, words kept).
  * ring is a STABLE hashed colour (FNV-1a over the name -> muted HSV hex) so every
    token reads as a distinct occult game-piece, deterministically.
  * timeline is the SCENE-ID NAMING CONVENTION '<npc_snake_case>_<beat>' with beat
    "intro" (E1a generates the timelines in parallel; the overworld falls back to
    the NPC's authored barks until the .dtl exists — recorded in _INGEST_NOTES_E1C).
  * bark_key names the voice_library region-bark key when voice.json carries it.
  * the VERDANT hand-wired cast (OverworldContent.NPC_DEFS) stays canonical in-game;
    verdant entries here are data for later reconciliation.

Deterministic: a re-run over unchanged sources is byte-identical.

Run:  python -B tools/ingest_casts.py          (writes client/catalog/npc_casts.json)
      python -B tools/ingest_casts.py --check  (verifies the committed file is current)
"""

from __future__ import annotations

import argparse
import colorsys
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_REGIONAL = os.path.join(ROOT, "docs", "content", "regional_cast.md")
SRC_FACTIONS = os.path.join(ROOT, "docs", "content", "factions_npcs.md")
VOICE = os.path.join(ROOT, "client", "catalog", "voice.json")
OUT_PATH = os.path.join(ROOT, "client", "catalog", "npc_casts.json")
OUT_NOTES = os.path.join(ROOT, "docs", "content", "_INGEST_NOTES_E1C_CASTS.md")

GENERATED = (
    "GENERATED by tools/ingest_casts.py from docs/content/regional_cast.md + "
    "docs/content/factions_npcs.md — edit the source, re-run the tool"
)

SCENE_CONVENTION = "<npc_snake_case>_<beat>"

# Region heading -> region id (region_layouts.json ids; maw_beneath/hollow_atelier are
# reserved for the regions that have not landed in the layouts yet).
REGION_HEADINGS = {
    "Threshold": "threshold",
    "The Verdant Glut": "verdant_glut",
    "The Mournmarch": "mournmarch",
    "Forgefell": "forgefell",
    "The Storm Vault": "storm_vault",
    "The Sunder": "the_sunder",
    "Titanfall": "titanfall",
    "The Tideless": "the_tideless",
    "The Astral Tier": "astral_tier",
    "The Maw Beneath": "maw_beneath",
    "The Hollow Atelier": "hollow_atelier",
}

# Faction -> (faction_id, home region). The Revel shares Verdant/Sunder; its cast homes
# to the_sunder because verdant's hand-wired cast stays canonical (recorded decision).
FACTIONS = {
    "The Concord": ("concord", "astral_tier"),
    "The Iron Guild": ("iron_guild", "forgefell"),
    "The Pale Court": ("pale_court", "mournmarch"),
    "The High Table": ("high_table", "storm_vault"),
    "The Stoneblooded": ("stoneblooded", "titanfall"),
    "The Bloomwardens": ("bloomwardens", "verdant_glut"),
    "The Revel": ("revel", "the_sunder"),
    "The Unbound": ("unbound", "the_sunder"),
    "The Deep Choir": ("deep_choir", "the_tideless"),
}

# Faction tokens searched (longest first) in an NPC's role/location text.
FACTION_TOKENS = [
    ("Bloomwarden", "bloomwardens"),
    ("Iron Guild", "iron_guild"),
    ("Pale Court", "pale_court"),
    ("High Table", "high_table"),
    ("Stoneblooded", "stoneblooded"),
    ("Deep Choir", "deep_choir"),
    ("Concord", "concord"),
    ("Unbound", "unbound"),
    ("Revel", "revel"),
]

_REGION_HEAD_RE = re.compile(r"^## (?:\d+\. )?(?P<title>[^(—]+?)(?: —| \()")
_NPC_RE = re.compile(
    r"^\*\*(?:\d+|[A-Z]{1,2}-\d+)\. (?P<name>[^*]+)\*\*(?: \*\([^)]*\)\*)? — \*(?P<role>[^*]+?)\.?\*"
)
_BARK_RE = re.compile(r"^- \*(?P<bark>.+?)\*\s*$")
_FACTION_HEAD_RE = re.compile(r"^## \d+\. (?P<name>The [\w' ]+?) — \*")
_LEADER_RE = re.compile(r"^### Leader — \*\*(?P<name>[^*]+)\*\*")
_HAND_RE = re.compile(
    r"^- \*\*(?P<name>[^*]+)\*\*(?: \*\([^)]*\)\*)? — \*(?P<role>[^*]+?)\.?\*(?P<rest>.*)$"
)
_TIER_RE = re.compile(r"^- \*\*(?P<tier>Stranger|Associate|Sworn|Champion|Hand):\*\* \*(?P<line>.+?)\*\s*$")
_QUOTE_RE = re.compile(r"[\"“](?P<quote>[^\"“”]+)[\"”]\s*$")


def strip_emphasis(text: str) -> str:
    text = text.replace("**", "")
    text = re.sub(r"(?<![\w])\*|\*(?![\w])", "", text)
    return re.sub(r"\s+", " ", text).strip()


def snake(name: str) -> str:
    text = name.strip().lower()
    text = re.sub(r"[^a-z0-9]+", "_", text)
    return text.strip("_")


def fnv1a32(text: str) -> int:
    h = 2166136261
    for b in text.encode("utf-8"):
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def ring_for(name: str) -> str:
    """Stable muted ring colour hashed from the name (grimoire-adjacent saturation/value)."""
    h = fnv1a32(name)
    hue = (h % 360) / 360.0
    sat = 0.34 + ((h >> 9) % 22) / 100.0
    val = 0.58 + ((h >> 17) % 22) / 100.0
    r, g, b = colorsys.hsv_to_rgb(hue, sat, val)
    return "#%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))


def faction_of(text: str) -> str:
    for token, fid in FACTION_TOKENS:
        if token in text:
            return fid
    return ""


def npc_entry(name: str, role: str, faction: str, barks: list, source: str, bark_key: str) -> dict:
    return {
        "name": name,
        "role": role,
        "faction": faction,
        "ring": ring_for(name),
        "timeline": snake(name) + "_intro",
        "bark_key": bark_key,
        "barks": barks,
        "source": source,
    }


def parse_cast_doc(path: str, source_tag: str, voice_keys: set, regions: dict) -> None:
    """Parse a region-sectioned cast doc (regional_cast.md / factions_npcs.md PART TWO +
    wanderers) appending entries into `regions`."""
    with open(path, encoding="utf-8") as fh:
        lines = fh.read().splitlines()
    region = ""
    current: dict | None = None
    for line in lines:
        if line.startswith("## "):
            current = None
            if line.startswith("## Wanderers"):
                region = "wanderers"
                continue
            m = _REGION_HEAD_RE.match(line)
            title = m.group("title").strip() if m else ""
            region = REGION_HEADINGS.get(title, "")
            continue
        if region == "":
            continue
        m = _NPC_RE.match(line)
        if m:
            name = strip_emphasis(m.group("name"))
            role = strip_emphasis(m.group("role"))
            bark_key = "bark.region.%s" % region if "bark.region.%s" % region in voice_keys else ""
            current = npc_entry(name, role, faction_of(line), [], source_tag, bark_key)
            regions.setdefault(region, []).append(current)
            continue
        if current is not None:
            b = _BARK_RE.match(line)
            if b:
                current["barks"].append(strip_emphasis(b.group("bark")))
            elif line.strip() == "" or line.startswith(("###", "---")):
                current = None


def parse_factions(voice_keys: set, regions: dict) -> None:
    """Parse PART ONE of factions_npcs.md: each faction's leader (+ standing-tier lines
    as barks) and 3 Hands (+ their embedded quote) into the faction's home region."""
    with open(SRC_FACTIONS, encoding="utf-8") as fh:
        text = fh.read()
    part_one = text.split("# PART TWO")[0]
    faction_name = ""
    leader: dict | None = None
    in_hands = False
    for line in part_one.splitlines():
        m = _FACTION_HEAD_RE.match(line)
        if m and m.group("name") in FACTIONS:
            faction_name = m.group("name")
            leader = None
            in_hands = False
            continue
        if faction_name == "":
            continue
        fid, region = FACTIONS[faction_name]
        bark_key = "bark.region.%s" % region if "bark.region.%s" % region in voice_keys else ""
        m = _LEADER_RE.match(line)
        if m:
            leader = npc_entry(
                strip_emphasis(m.group("name")),
                "faction leader",
                fid,
                [],
                "factions_npcs.md leader",
                bark_key,
            )
            regions.setdefault(region, []).append(leader)
            in_hands = False
            continue
        if line.startswith("### Hands"):
            in_hands = True
            continue
        if line.startswith("### "):
            in_hands = False
            continue
        t = _TIER_RE.match(line)
        if t and leader is not None:
            leader["barks"].append(strip_emphasis(t.group("line")))
            continue
        if in_hands:
            h = _HAND_RE.match(line)
            if h:
                barks = []
                q = _QUOTE_RE.search(strip_emphasis(h.group("rest")))
                if q:
                    barks.append(q.group("quote").strip())
                regions.setdefault(region, []).append(
                    npc_entry(
                        strip_emphasis(h.group("name")),
                        strip_emphasis(h.group("role")),
                        fid,
                        barks,
                        "factions_npcs.md hand",
                        bark_key,
                    )
                )


def build(check: bool) -> int:
    with open(VOICE, encoding="utf-8") as fh:
        voice_keys = set(json.load(fh).keys())
    regions: dict = {}
    parse_factions(voice_keys, regions)
    parse_cast_doc(SRC_REGIONAL, "regional_cast.md", voice_keys, regions)
    parse_cast_doc(SRC_FACTIONS, "factions_npcs.md roster", voice_keys, regions)

    ordered = {rid: regions[rid] for rid in sorted(regions)}
    doc = {
        "_generated": GENERATED,
        "_contract": (
            "DATA ONLY — per-region NPC defs (VERBATIM names/roles/barks; stable hashed ring "
            "colours). timeline follows the shared scene-id convention; the overworld falls "
            "back to barks until the timeline resource exists. The verdant hand-wired cast "
            "(OverworldContent.NPC_DEFS) keeps precedence in-game."
        ),
        "scene_id_convention": SCENE_CONVENTION,
        "regions": ordered,
    }
    payload = json.dumps(doc, ensure_ascii=False, indent=2) + "\n"
    notes = [
        "# _INGEST_NOTES_E1C_CASTS — regional casts as data",
        "",
        GENERATED + ".",
        "",
        "## Decisions",
        "",
        "- **Scene id naming convention** (shared with E1a's generated timelines):",
        "  `%s` — npc_casts.json references beat `intro`; the overworld" % SCENE_CONVENTION,
        "  bubbles the NPC's authored barks until the timeline resource exists.",
        "- **The Revel homes to `the_sunder`** (its shared Verdant/Sunder turf): the verdant",
        "  hand-wired cast (OverworldContent.NPC_DEFS) stays canonical in-game.",
        "- **Ring colours** are FNV-1a hashes of the VERBATIM name mapped into a muted HSV",
        "  band — stable across re-runs, distinct per NPC.",
        "- **Faction homes:** " + "; ".join(
            "%s → `%s`" % (fid, region) for _n, (fid, region) in sorted(FACTIONS.items())
        ) + ".",
        "",
        "## Per-region counts",
        "",
    ]
    for rid, entries in ordered.items():
        notes.append("- `%s` — %d NPCs" % (rid, len(entries)))
    notes_text = "\n".join(notes) + "\n"

    outputs = [(OUT_PATH, payload), (OUT_NOTES, notes_text)]
    if check:
        stale = []
        for path, text in outputs:
            current = ""
            if os.path.exists(path):
                with open(path, encoding="utf-8") as fh:
                    current = fh.read()
            if current != text:
                stale.append(os.path.relpath(path, ROOT))
        if stale:
            print("STALE: %s (re-run tools/ingest_casts.py)" % ", ".join(stale), file=sys.stderr)
            return 1
        print("npc_casts.json / notes are current.")
        return 0
    for path, text in outputs:
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    total = sum(len(v) for v in ordered.values())
    print("wrote %d NPCs across %d region keys:" % (total, len(ordered)))
    for rid, entries in ordered.items():
        print("  %-16s %d" % (rid, len(entries)))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    return build(args.check)


if __name__ == "__main__":
    sys.exit(main())
