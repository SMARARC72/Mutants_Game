#!/usr/bin/env python3
"""Ingest the authored endings doc into the endings catalog (Batch E2b).

Parses docs/content/endgame_succession.md PART ONE (the eleven endings) and emits
client/catalog/endings.json: every ending as {id, name, epithet, grid, epigraph,
conditions, priority} plus ONE documented fallback entry (empty conditions,
priority 0) so EndingsService.resolve() can never come back empty-handed once the
finale flag lands.

Epigraphs land VERBATIM (only markdown emphasis markers are stripped — the
voice-ingest precedent). Where the doc is structurally ambiguous the tool makes
the CONSERVATIVE choice and records it in tools/INGEST_NOTES.md (between its
ownership markers) — no silent inventions:
  * the epigraph is each ending's own-voice line: the authored `mid-reign`
    quote for the nine ascensions, `in the Atelier` for the God-Maker, and the
    Unmaking coda ("the one un-ironic line") for the Unmaking;
  * the nine grid endings condition on the 3x3 morality grid EXACTLY as
    CharacterEngine bands it: god_alignment = the Order<->Chaos band label, and
    corruption_min/corruption_max = the Purity<->Corrupt band bounds (band3
    thresholds +/-34 over the clamped axis). The cumulative occult-corruption
    price meter (ADR-014) is a DIFFERENT track; no authored ending conditions
    on it;
  * the two refusals condition on their door flags: `unmaking` (the doc's own
    UNMAKING run-flag, lowercased to the engine flag convention) and
    `god_maker` (slug of the Q4.4 door title) — wave/e2-arc wires the setters,
    the integrator reconciles;
  * the fallback entry reuses the authored Act-5 climax title ("A Graveyard of
    Winners") and the doc's closing load-screen line — no new lore is minted.

Deterministic: a re-run over unchanged sources is byte-identical (doc ordering,
LF newlines, no timestamps).

Run:  python -B tools/ingest_endings.py          (writes client/catalog/endings.json)
      python -B tools/ingest_endings.py --check  (verifies the committed file is current)
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC_PATH = os.path.join(ROOT, "docs", "content", "endgame_succession.md")
OUT_PATH = os.path.join(ROOT, "client", "catalog", "endings.json")
NOTES_PATH = os.path.join(ROOT, "tools", "INGEST_NOTES.md")
NOTES_BEGIN = "<!-- BEGIN ingest_endings.py (generated census — do not edit) -->"
NOTES_END = "<!-- END ingest_endings.py -->"

GENERATED_HEADER = (
    "GENERATED by tools/ingest_endings.py from docs/content/endgame_succession.md "
    "— edit the source, re-run the tool."
)

# The 3x3 grid bands, exactly as the oracle/CharacterEngine band3 splits them
# (v <= -34 -> left label, v >= 34 -> right label, else middle).
OC_LABELS = ("Order", "Balanced", "Chaos")
PC_BANDS = {
    "Pure": {"corruption_max": -34},
    "Tainted": {"corruption_min": -33, "corruption_max": 33},
    "Corrupt": {"corruption_min": 34},
}

# The two refusal doors -> their run flags (recorded decision; e2-arc wires the setters).
DOOR_FLAGS = {
    "refuse the throne": "god_maker",
    "kill the Primordials": "unmaking",
}

# Resolve order: the true/secret ending outranks the refusal-by-pride, which
# outranks the nine grid ascensions (mutually exclusive by grid), which outrank
# the always-true fallback.
PRIORITY_UNMAKING = 110
PRIORITY_GOD_MAKER = 100
PRIORITY_GRID = 50
PRIORITY_FALLBACK = 0

_EMPH_RE = re.compile(r"\*\*|\*|`")
_HEADING_RE = re.compile(r"^## ENDING (\d+) — (.+?) \((.+?)\)(?: · \*(.+?)\*)?\s*$")
_QUOTE_RE = re.compile(r'^> \*(.+?):\*\s*(".*")\s*$')
_FALLBACK_LINE_RE = re.compile(r'"(the gods are mostly dead[^"]*)"')

# The one own-voice quote per ending kind (recorded decision — see INGEST_NOTES).
EPIGRAPH_MARKERS = ("mid-reign", "in the Atelier", "the Unmaking coda")


def strip_emphasis(text: str) -> str:
    """Markdown emphasis markers off; the words stay verbatim."""
    return _EMPH_RE.sub("", text).strip()


def slug(text: str) -> str:
    """Deterministic id fragment from a name (mirrors ingest_quests.slug)."""
    text = text.strip().lower()
    text = re.sub(r"[''`]", "", text)
    return re.sub(r"[^a-z0-9]+", "_", text).strip("_")


def title_case(name: str) -> str:
    """THE LAWGIVER -> The Lawgiver (hyphens keep both halves cased)."""
    return name.title()


def conditions_for(grid_tag: str, number: int) -> tuple[dict, str, int]:
    """(conditions, grid_key, priority) from a heading's parenthesised tag."""
    if grid_tag in DOOR_FLAGS:
        flag = DOOR_FLAGS[grid_tag]
        priority = PRIORITY_UNMAKING if flag == "unmaking" else PRIORITY_GOD_MAKER
        return {"flags_all": [flag]}, "", priority
    parts = [p.strip() for p in grid_tag.split("·")]
    if len(parts) != 2 or parts[0] not in OC_LABELS or parts[1] not in PC_BANDS:
        raise SystemExit("ENDING %d: unrecognised grid tag '%s'" % (number, grid_tag))
    conditions: dict = {"god_alignment": parts[0]}
    conditions.update(PC_BANDS[parts[1]])
    return conditions, "%s|%s" % (parts[0], parts[1]), PRIORITY_GRID


def epigraph_from(block: list[str], number: int) -> tuple[str, str]:
    """The ending's own-voice quote (VERBATIM, emphasis stripped) + its marker."""
    for line in block:
        m = _QUOTE_RE.match(line)
        if not m:
            continue
        speaker = m.group(1)
        for marker in EPIGRAPH_MARKERS:
            if marker in speaker:
                return strip_emphasis(m.group(2)).strip('"'), marker
    raise SystemExit("ENDING %d: no own-voice epigraph line found" % number)


def parse_endings(text: str) -> list[dict]:
    lines = text.split("\n")
    endings: list[dict] = []
    i = 0
    while i < len(lines):
        m = _HEADING_RE.match(lines[i])
        if not m:
            i += 1
            continue
        number, raw_name, grid_tag = int(m.group(1)), m.group(2), m.group(3)
        epithet = strip_emphasis(m.group(4) or "")
        block: list[str] = []
        i += 1
        while i < len(lines) and not lines[i].startswith("## "):
            block.append(lines[i])
            i += 1
        name = title_case(strip_emphasis(raw_name))
        conditions, grid_key, priority = conditions_for(grid_tag.strip(), number)
        epigraph, marker = epigraph_from(block, number)
        endings.append(
            {
                "id": slug(name),
                "ending": number,
                "name": name,
                "epithet": epithet,
                "grid": grid_key,
                "epigraph": epigraph,
                "conditions": conditions,
                "priority": priority,
                "_epigraph_source": marker,  # census only; popped before emit
            }
        )
    return sorted(endings, key=lambda e: e["ending"])


def fallback_entry(text: str) -> dict:
    """The documented always-true fallback: the authored Act-5 climax title +
    the doc's closing load-screen line. resolve() can never return null."""
    m = _FALLBACK_LINE_RE.search(text)
    if not m:
        raise SystemExit("closing load-screen line not found for the fallback entry")
    return {
        "id": "a_graveyard_of_winners",
        "name": "A Graveyard of Winners",
        "epithet": "",
        "grid": "",
        "epigraph": strip_emphasis(m.group(1)),
        "conditions": {},
        "priority": PRIORITY_FALLBACK,
        "fallback": True,
    }


def notes_section(endings: list[dict]) -> str:
    out = [NOTES_BEGIN, ""]
    grid_count = sum(1 for e in endings if e["grid"])
    out.append(
        "**Counts (actuals):** %d authored endings (%d grid ascensions + 2 refusals) "
        "+ 1 fallback. The doc promises 11." % (len(endings), grid_count)
    )
    out.append("")
    out.append("**Per-ending census (id · grid/door · epigraph source · priority):**")
    for e in endings:
        door = e["grid"] if e["grid"] else "/".join(e["conditions"].get("flags_all", []))
        out.append(
            "- %s · %s · %s · %d"
            % (e["id"], door, e.get("_epigraph_source", ""), e["priority"])
        )
    out.append("- a_graveyard_of_winners · (fallback, always true) · closing line · 0")
    out.append("")
    out.append(NOTES_END)
    return "\n".join(out)


def splice_notes(section: str) -> None:
    """Replace this tool's marker-delimited section of INGEST_NOTES.md in place."""
    with open(NOTES_PATH, "r", encoding="utf-8") as fh:
        text = fh.read()
    begin = text.find(NOTES_BEGIN)
    end = text.find(NOTES_END)
    if begin < 0 or end < 0:
        raise SystemExit("INGEST_NOTES.md is missing the ingest_endings.py markers")
    new_text = text[:begin] + section + text[end + len(NOTES_END) :]
    with open(NOTES_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(new_text)


def build() -> tuple[str, str]:
    with open(DOC_PATH, "r", encoding="utf-8") as fh:
        text = fh.read()
    endings = parse_endings(text)
    if len(endings) != 11:
        raise SystemExit("expected 11 authored endings, parsed %d" % len(endings))
    notes = notes_section(endings)
    emitted = []
    for e in endings:
        clean = dict(e)
        clean.pop("_epigraph_source", None)
        emitted.append(clean)
    emitted.append(fallback_entry(text))
    ids = [e["id"] for e in emitted]
    if len(set(ids)) != len(ids):
        raise SystemExit("duplicate ending ids")
    payload = {
        "_generated": GENERATED_HEADER,
        "counts": {"endings": 11, "fallback": 1},
        "endings": emitted,
    }
    catalog = json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    return catalog, notes


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog, notes = build()
    if args.check:
        with open(OUT_PATH, "r", encoding="utf-8") as fh:
            if fh.read() != catalog:
                print("STALE: client/catalog/endings.json — re-run tools/ingest_endings.py")
                return 1
        print("endings.json is current")
        return 0
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(catalog)
    splice_notes(notes)
    data = json.loads(catalog)
    print(
        "wrote %s: %d endings + %d fallback"
        % (
            os.path.relpath(OUT_PATH, ROOT),
            data["counts"]["endings"],
            data["counts"]["fallback"],
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
