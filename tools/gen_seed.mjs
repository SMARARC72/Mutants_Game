#!/usr/bin/env node
/**
 * gen_seed.mjs — emit supabase/seed.sql from the in-repo catalog bundle (ADR-006, D2).
 * The DB mirror (seed) and the client bundle come from ONE source: client/catalog/*.json
 * (themselves produced by tools/gen_catalog.mjs). Catalog tables only — never per-player data.
 *
 * Run: node tools/gen_catalog.mjs && node tools/gen_seed.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CAT = join(ROOT, "client", "catalog");
const read = (f) => JSON.parse(readFileSync(join(CAT, f), "utf8"));

const species = read("species.json").species;
const gear = read("gear.json").gear;
const skills = read("skills.json").skills;
const factions = read("factions.json").factions;

const sql = (v) => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return "'" + String(v).replace(/'/g, "''") + "'";
};
const arr = (a) => (!a || a.length === 0 ? "NULL" : "ARRAY[" + a.map(sql).join(", ") + "]::text[]");
const jsonb = (o) => (o === null || o === undefined ? "NULL" : "'" + JSON.stringify(o).replace(/'/g, "''") + "'::jsonb");

function insert(table, cols, rows, tuple, conflict) {
  if (rows.length === 0) return "";
  const vals = rows.map((r) => "  (" + tuple(r).join(", ") + ")").join(",\n");
  return (
    `insert into ${table} (${cols.join(", ")}) values\n${vals}\n` +
    `on conflict (${conflict}) do nothing;\n\n`
  );
}

let out = "-- seed.sql — GENERATED by tools/gen_seed.mjs from client/catalog/*.json — DO NOT EDIT.\n";
out += "-- Catalog (static) data only: species, gear, skills, factions (ADR-006). Runs after\n";
out += "-- migrations on `supabase db reset` as the postgres role (bypasses RLS).\n\n";
out += "begin;\n\n";

out += insert(
  "species",
  ["id", "name", "batch", "art_ref", "class", "rank", "tier", "force_primary",
   "force_secondary", "role", "evolution_line", "stage", "signature_skill", "tags",
   "description", "status"],
  species,
  (s) => [
    sql(s.id), sql(s.name), sql(s.batch), sql(s.art_ref), sql(s.class), sql(s.rank),
    sql(s.tier), sql(s.force_primary), sql(s.force_secondary), sql(s.role),
    sql(s.evolution_line), sql(s.stage), sql(s.signature_skill), arr(s.tags),
    sql(s.description), sql(s.status),
  ],
  "id"
);

out += insert(
  "gear",
  ["id", "name", "slot", "rarity", "force", "effects"],
  gear,
  (g) => [sql(g.id), sql(g.name), sql(g.slot), sql(g.rarity), sql(g.force), jsonb(g.effects)],
  "id"
);

out += insert(
  "skills",
  ["id", "name", "force", "verb", "ap", "focus", "effect"],
  skills,
  (s) => [sql(s.id), sql(s.name), sql(s.force), sql(s.verb), sql(s.ap), sql(s.focus), jsonb(s.effect)],
  "id"
);

out += insert(
  "factions",
  ["id", "name", "region", "god", "grid", "ideology"],
  factions,
  (f) => [sql(f.id), sql(f.name), sql(f.region), sql(f.god), sql(f.grid), sql(f.ideology)],
  "id"
);

out += "commit;\n";

writeFileSync(join(ROOT, "supabase", "seed.sql"), out);
console.log(`seed.sql: ${species.length} species, ${gear.length} gear, ${skills.length} skills, ${factions.length} factions`);
